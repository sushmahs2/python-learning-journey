
# DAY 1: Arithmetic Operations in Python

# 1. Addition: Adds two numbers
a = 35 + 56
print(a)  # Output: 91

# 2. Subtraction: Subtracts the second number from the first
b = 65 - 34
print(b)  # Output: 31

# 3. Multiplication: Multiplies two numbers
c = 23 * 56
print(c)  # Output: 1288

# 4. Division: Divides one number by another
d = 25 / 5
print(d)  # Output: 5.0

# 5. Floor Division: Returns the quotient rounded down
e = 26 // 5
print(e)  # Output: 5

# 6. Modulus: Returns the remainder after division
f = 26 % 5
print(f)  # Output: 1
